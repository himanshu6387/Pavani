const express = require("express");

const router = express.Router();


// ============================================================
// CONTROLLER
// ============================================================

const {
  register,
  login,
  getMe,
  logout,
} = require("../controllers/authController");


// ============================================================
// MIDDLEWARE
// ============================================================

const protect =
  require("../middleware/authMiddleware");


// ============================================================
// REGISTER
// POST /api/auth/register
// ============================================================

router.post(
  "/register",
  register
);


// ============================================================
// LOGIN
// POST /api/auth/login
// ============================================================

router.post(
  "/login",
  login
);


// ============================================================
// CURRENT USER
// GET /api/auth/me
// ============================================================

router.get(
  "/me",
  protect,
  getMe
);


// ============================================================
// LOGOUT
// POST /api/auth/logout
// ============================================================

router.post(
  "/logout",
  protect,
  logout
);


// ============================================================
// EXPORT
// ============================================================

module.exports = router;