const mongoose = require("mongoose");


// ============================================================
// FORM FILL SCHEMA
// ============================================================

const formFillSchema = new mongoose.Schema(

  {

    // ========================================================
    // USER
    // ========================================================

    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true
    },


    // ========================================================
    // FORM NAME
    // ========================================================

    formName: {
      type: String,
      required: true,
      trim: true
    },


    // ========================================================
    // FORM DESCRIPTION
    // ========================================================

    description: {
      type: String,
      default: "",
      trim: true
    },


    // ========================================================
    // SOURCE DOCUMENTS
    // ========================================================

    sourceDocuments: [
      {
        type: mongoose.Schema.Types.ObjectId,
        ref: "Document"
      }
    ],


    // ========================================================
    // FORM FIELDS
    // ========================================================

    fields: [
      {

        // ----------------------------------------------------
        // FIELD NAME
        // ----------------------------------------------------

        fieldName: {
          type: String,
          required: true,
          trim: true
        },


        // ----------------------------------------------------
        // FIELD LABEL
        // ----------------------------------------------------

        label: {
          type: String,
          required: true,
          trim: true
        },


        // ----------------------------------------------------
        // FIELD TYPE
        // ----------------------------------------------------

        fieldType: {
          type: String,
          enum: [
            "text",
            "number",
            "date",
            "email",
            "phone",
            "address",
            "select",
            "textarea",
            "other"
          ],
          default: "text"
        },


        // ----------------------------------------------------
        // AI SUGGESTED VALUE
        // ----------------------------------------------------

        suggestedValue: {
          type: String,
          default: ""
        },


        // ----------------------------------------------------
        // USER EDITED VALUE
        // ----------------------------------------------------

        finalValue: {
          type: String,
          default: ""
        },


        // ----------------------------------------------------
        // SOURCE
        // ----------------------------------------------------

        sourceDocument: {
          type: mongoose.Schema.Types.ObjectId,
          ref: "Document",
          default: null
        },


        // ----------------------------------------------------
        // SOURCE TEXT
        // ----------------------------------------------------

        sourceText: {
          type: String,
          default: ""
        },


        // ----------------------------------------------------
        // CONFIDENCE
        // ----------------------------------------------------

        confidence: {
          type: Number,
          min: 0,
          max: 100,
          default: 0
        },


        // ----------------------------------------------------
        // REQUIRED FIELD
        // ----------------------------------------------------

        required: {
          type: Boolean,
          default: false
        },


        // ----------------------------------------------------
        // VERIFIED BY USER
        // ----------------------------------------------------

        verified: {
          type: Boolean,
          default: false
        }

      }
    ],


    // ========================================================
    // STATUS
    // ========================================================

    status: {
      type: String,
      enum: [
        "draft",
        "processing",
        "ready",
        "completed"
      ],
      default: "draft"
    },


    // ========================================================
    // AI PROCESSING STATUS
    // ========================================================

    aiProcessed: {
      type: Boolean,
      default: false
    },


    // ========================================================
    // COMPLETION
    // ========================================================

    completionPercentage: {
      type: Number,
      min: 0,
      max: 100,
      default: 0
    }

  },

  {
    timestamps: true
  }

);


// ============================================================
// INDEXES
// ============================================================

formFillSchema.index({
  user: 1,
  createdAt: -1
});

formFillSchema.index({
  user: 1,
  status: 1
});


// ============================================================
// EXPORT
// ============================================================

module.exports =
  mongoose.model(
    "FormFill",
    formFillSchema
  );