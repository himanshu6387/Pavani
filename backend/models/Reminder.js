const mongoose = require("mongoose");

const reminderSchema = new mongoose.Schema(
  {
    // ========================================================
    // OWNER
    // ========================================================

    owner: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },

    // ========================================================
    // RELATED DOCUMENT
    // ========================================================

    document: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Document",
      default: null,
    },

    // ========================================================
    // TITLE
    // ========================================================

    title: {
      type: String,
      required: true,
      trim: true,
    },

    // ========================================================
    // DESCRIPTION
    // ========================================================

    description: {
      type: String,
      default: "",
      trim: true,
    },

    // ========================================================
    // REMINDER DATE
    // ========================================================

    reminderDate: {
      type: Date,
      required: true,
      index: true,
    },

    // ========================================================
    // REMINDER TYPE
    // ========================================================

    type: {
      type: String,
      enum: [
        "expiry",
        "custom",
        "document",
        "medical",
        "financial",
        "insurance",
        "general",
      ],
      default: "general",
    },

    // ========================================================
    // PRIORITY
    // ========================================================

    priority: {
      type: String,
      enum: [
        "low",
        "medium",
        "high",
      ],
      default: "medium",
    },

    // ========================================================
    // STATUS
    // ========================================================

    status: {
      type: String,
      enum: [
        "pending",
        "completed",
        "dismissed",
      ],
      default: "pending",
      index: true,
    },

    // ========================================================
    // NOTIFICATION
    // ========================================================

    notificationSent: {
      type: Boolean,
      default: false,
    },

    // ========================================================
    // AUTO GENERATED
    // ========================================================

    autoGenerated: {
      type: Boolean,
      default: false,
    },
  },

  {
    timestamps: true,
  }
);


// ============================================================
// INDEXES
// ============================================================

reminderSchema.index({
  owner: 1,
  reminderDate: 1,
});

reminderSchema.index({
  owner: 1,
  status: 1,
});


// ============================================================
// EXPORT
// ============================================================

module.exports = mongoose.model(
  "Reminder",
  reminderSchema
);