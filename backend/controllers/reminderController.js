// GENERATE AUTOMATIC EXPIRY REMINDERS
// POST /api/reminders/generate
// ============================================================

const generateReminders =
  async (req, res) => {

    try {

      if (!req.user) {
        return res.status(401).json({
          success: false,
          message:
            "Unauthorized.",
        });
      }


      // ======================================================
      // GET DOCUMENTS HAVING EXPIRY
      // ======================================================

      const documents =
        await Document.find({

          owner:
            req.user._id,

          expiryDate: {
            $ne: null,
          },

        });


      const generated =
        [];


      const now =
        new Date();


      // ======================================================
      // PROCESS DOCUMENTS
      // ======================================================

      for (
        const document of documents
      ) {

        if (
          !document.expiryDate
        ) {
          continue;
        }


        const expiryDate =
          new Date(
            document.expiryDate
          );


        if (
          Number.isNaN(
            expiryDate.getTime()
          )
        ) {
          continue;
        }


        // ----------------------------------------------------
        // ALREADY EXPIRED
        // ----------------------------------------------------

        if (
          expiryDate <= now
        ) {
          continue;
        }


        const difference =
          expiryDate.getTime() -
          now.getTime();


        const days =
          Math.ceil(
            difference /
              (
                1000 *
                60 *
                60 *
                24
              )
          );


        // ----------------------------------------------------
        // REMINDER DATE
        // ----------------------------------------------------

        let daysBefore = 30;

        let priority =
          "medium";


        if (days <= 7) {

          daysBefore = 1;

          priority =
            "high";

        } else if (days <= 30) {

          daysBefore = 7;

          priority =
            "high";

        } else {

          daysBefore = 30;

          priority =
            "medium";
        }


        const reminderDate =
          new Date(
            expiryDate
          );


        reminderDate.setDate(
          reminderDate.getDate() -
            daysBefore
        );


        if (
          reminderDate < now
        ) {

          reminderDate.setTime(
            now.getTime()
          );

        }


        // ----------------------------------------------------
        // DUPLICATE CHECK
        // ----------------------------------------------------

        const duplicate =
          await Reminder.findOne({

            owner:
              req.user._id,

            document:
              document._id,

            type:
              "expiry",

            status:
              "pending",

          });


        if (duplicate) {
          continue;
        }


        // ----------------------------------------------------
        // CREATE
        // ----------------------------------------------------

        const reminder =
          await Reminder.create({

            owner:
              req.user._id,

            document:
              document._id,

            title:
              days <= 7
                ? `Urgent: ${document.originalName} expires soon`
                : `Expiry reminder: ${document.originalName}`,

            description:
              `Document expiry date: ${expiryDate.toISOString().split("T")[0]}`,

            reminderDate:
              reminderDate,

            type:
              "expiry",

            priority:
              priority,

            status:
              "pending",

            notificationSent:
              false,

            autoGenerated:
              true,

          });


        await reminder.populate(
          "document",
          "originalName category expiryDate"
        );


        generated.push(
          reminder
        );
      }


      return res.status(200).json({

        success: true,

        message:
          generated.length
            ? "Expiry reminders generated successfully."
            : "No new expiry reminders required.",

        count:
          generated.length,

        reminders:
          generated,

      });

    } catch (error) {

      console.error(
        "Generate reminders error:",
        error
      );

      return res.status(500).json({

        success: false,

        message:
          "Failed to generate reminders.",

        error:
          process.env.NODE_ENV ===
          "development"
            ? error.message
            : undefined,

      });
    }
  };



