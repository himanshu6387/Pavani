const mongoose = require("mongoose");

const Reminder = require("../models/Reminder");
const Document = require("../models/Document");


// ============================================================
// CREATE REMINDER
// POST /api/reminders
// ============================================================

const createReminder = async (req, res) => {
  try {

    if (!req.user) {
      return res.status(401).json({
        success: false,
        message: "Unauthorized.",
      });
    }


    const {
      title,
      description,
      reminderDate,
      type,
      priority,
      document,
    } = req.body;


    // ========================================================
    // VALIDATION
    // ========================================================

    if (!title || !title.trim()) {
      return res.status(400).json({
        success: false,
        message: "Reminder title is required.",
      });
    }


    if (!reminderDate) {
      return res.status(400).json({
        success: false,
        message: "Reminder date is required.",
      });
    }


    const parsedDate =
      new Date(reminderDate);


    if (
      Number.isNaN(
        parsedDate.getTime()
      )
    ) {
      return res.status(400).json({
        success: false,
        message: "Invalid reminder date.",
      });
    }


    // ========================================================
    // DOCUMENT VALIDATION
    // ========================================================

    let documentId = null;


    if (document) {

      if (
        !mongoose.Types.ObjectId.isValid(
          document
        )
      ) {
        return res.status(400).json({
          success: false,
          message: "Invalid document ID.",
        });
      }


      const foundDocument =
        await Document.findOne({
          _id: document,
          owner: req.user._id,
        });


      if (!foundDocument) {
        return res.status(404).json({
          success: false,
          message:
            "Document not found.",
        });
      }


      documentId =
        foundDocument._id;
    }


    // ========================================================
    // CREATE
    // ========================================================

    const reminder =
      await Reminder.create({
        owner: req.user._id,

        document: documentId,

        title:
          title.trim(),

        description:
          description
            ? description.trim()
            : "",

        reminderDate:
          parsedDate,

        type:
          type || "general",

        priority:
          priority || "medium",

        status:
          "pending",

        notificationSent:
          false,

        autoGenerated:
          false,
      });


    // ========================================================
    // POPULATE
    // ========================================================

    await reminder.populate(
      "document",
      "originalName category expiryDate"
    );


    return res.status(201).json({
      success: true,
      message:
        "Reminder created successfully.",
      reminder,
    });

  } catch (error) {

    console.error(
      "Create reminder error:",
      error
    );

    return res.status(500).json({
      success: false,
      message:
        "Failed to create reminder.",
      error:
        process.env.NODE_ENV ===
        "development"
          ? error.message
          : undefined,
    });
  }
};



// ============================================================
// GET ALL REMINDERS
// GET /api/reminders
// ============================================================

const getReminders = async (req, res) => {
  try {

    if (!req.user) {
      return res.status(401).json({
        success: false,
        message: "Unauthorized.",
      });
    }


    const {
      status,
      type,
    } = req.query;


    const query = {
      owner: req.user._id,
    };


    if (
      status &&
      [
        "pending",
        "completed",
        "dismissed",
      ].includes(status)
    ) {
      query.status = status;
    }


    if (type) {
      query.type = type;
    }


    const reminders =
      await Reminder.find(query)
        .populate(
          "document",
          "originalName category expiryDate"
        )
        .sort({
          reminderDate: 1,
          createdAt: -1,
        });


    return res.status(200).json({
      success: true,
      count:
        reminders.length,
      reminders,
    });

  } catch (error) {

    console.error(
      "Get reminders error:",
      error
    );

    return res.status(500).json({
      success: false,
      message:
        "Failed to fetch reminders.",
      error:
        process.env.NODE_ENV ===
        "development"
          ? error.message
          : undefined,
    });
  }
};



