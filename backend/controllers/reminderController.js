// UPDATE REMINDER
// PUT /api/reminders/:id
// ============================================================

const updateReminder =
  async (req, res) => {

    try {

      if (!req.user) {
        return res.status(401).json({
          success: false,
          message:
            "Unauthorized.",
        });
      }


      if (
        !mongoose.Types.ObjectId.isValid(
          req.params.id
        )
      ) {
        return res.status(400).json({
          success: false,
          message:
            "Invalid reminder ID.",
        });
      }


      const allowed =
        [
          "title",
          "description",
          "reminderDate",
          "type",
          "priority",
          "status",
        ];


      const update = {};


      for (
        const field of allowed
      ) {

        if (
          req.body[field] !==
          undefined
        ) {

          update[field] =
            req.body[field];

        }
      }


      if (
        update.reminderDate
      ) {

        const date =
          new Date(
            update.reminderDate
          );


        if (
          Number.isNaN(
            date.getTime()
          )
        ) {
          return res.status(400).json({
            success: false,
            message:
              "Invalid reminder date.",
          });
        }


        update.reminderDate =
          date;
      }


      const reminder =
        await Reminder.findOneAndUpdate(

          {
            _id:
              req.params.id,

            owner:
              req.user._id,
          },

          update,

          {
            new: true,
            runValidators: true,
          }

        ).populate(
          "document",
          "originalName category expiryDate"
        );


      if (!reminder) {
        return res.status(404).json({
          success: false,
          message:
            "Reminder not found.",
        });
      }


      return res.status(200).json({

        success: true,

        message:
          "Reminder updated successfully.",

        reminder,

      });

    } catch (error) {

      console.error(
        "Update reminder error:",
        error
      );

      return res.status(500).json({

        success: false,

        message:
          "Failed to update reminder.",

      });
    }
  };



